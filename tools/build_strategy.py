#!/usr/bin/env python3
"""Generate the strategy() version of SignalTW from the indicator source.

Pine Script cannot share code between an indicator and a strategy, so the
strategy file is generated: the indicator stays the single source of truth
and this script swaps the declaration, drops alertcondition() (indicator
only) and fills the <<STRATEGY_*>> marker comments with order code.

Usage: python3 tools/build_strategy.py
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "SMC_OrderBlock_FVG_MTF.pine"
DST = ROOT / "SMC_OrderBlock_FVG_MTF_Strategy.pine"

DECL_RE = re.compile(r'^indicator\(.*?\)\n(?=\n)', re.S | re.M)

DECL = '''strategy("SignalTW - OB & FVG [MTF] Strategy", "SignalTW Strategy", overlay = true,
     max_boxes_count = 500, max_lines_count = 500, max_labels_count = 500, max_bars_back = 500,
     initial_capital = 10000, currency = currency.USD, pyramiding = 0, process_orders_on_close = true,
     commission_type = strategy.commission.cash_per_contract, commission_value = 0.25, slippage = 0,
     margin_long = 1, margin_short = 1)
'''

STATE = '''// ---- Strategy order state (generated by tools/build_strategy.py)
var int   stPendBar = na      // bar a pending limit entry was placed on
var float stTp      = na
var bool  stLong    = true
var float stQty     = 0.0
var int   stOpenBar = na
var bool  stBE      = false
'''

ENTRY = '''        // ---- Strategy orders (generated by tools/build_strategy.py)
        if strategy.position_size == 0
            float  stUnits = math.max(lotStep, math.floor(strategy.initial_capital * riskPct / 100 / (risk * lotUnits) / lotStep) * lotStep) * lotUnits
            string stId    = isBuy ? "Long" : "Short"
            strategy.cancel_all()
            strategy.entry(stId, isBuy ? strategy.long : strategy.short, qty = stUnits, limit = cLim ? cEntry : na, comment = (isBuy ? "BUY" : "SELL") + tag)
            if not na(tp1)
                strategy.exit("TP1", stId, qty_percent = tp1Pct, limit = tp1, stop = cSl, comment_profit = "TP1", comment_loss = "SL")
            strategy.exit("TP", stId, limit = tp, stop = cSl, comment_profit = "TP", comment_loss = "SL")
            stPendBar := cLim ? bar_index : na
            stTp      := tp
            stLong    := isBuy
            stQty     := stUnits
            stBE      := false
'''

MANAGE = '''// ---- Strategy order management (generated by tools/build_strategy.py)
bool stInPos = strategy.position_size != 0
if stInPos and not stInPos[1]
    stOpenBar := bar_index
    stPendBar := na
// Pending limit entry: cancel after the validity window, or when price reached the target without filling
if not stInPos and not na(stPendBar) and bar_index > stPendBar
    if bar_index - stPendBar > limitBars or (stLong ? high >= stTp : low <= stTp)
        strategy.cancel_all()
        stPendBar := na
// After the partial take-profit, move the stop of the remainder to the average entry price
if stInPos and partOn and not stBE and math.abs(strategy.position_size) < stQty * 0.999
    strategy.exit("TP", stLong ? "Long" : "Short", limit = stTp, stop = strategy.position_avg_price, comment_profit = "TP", comment_loss = "BE")
    stBE := true
// Time stop (bars since fill)
if stInPos and maxHold > 0 and bar_index - stOpenBar >= maxHold
    strategy.close_all(comment = "Time")
'''


def build() -> str:
    src = SRC.read_text(encoding="utf-8")

    out, n = DECL_RE.subn(DECL, src, count=1)
    if n != 1:
        sys.exit("indicator() declaration not found")

    out = out.replace(
        "// SignalTW - Order Block + Fair Value Gap + Market Structure (Multi-Timeframe)",
        "// SignalTW - Order Block + Fair Value Gap + Market Structure (Multi-Timeframe) - STRATEGY VERSION\n"
        "// GENERATED from SMC_OrderBlock_FVG_MTF.pine by tools/build_strategy.py - edit the indicator, then rebuild.",
        1,
    )

    # alertcondition() is indicator-only
    out = "\n".join(l for l in out.split("\n") if not l.startswith("alertcondition(")) + ("\n" if out.endswith("\n") else "")

    # The Strategy Tester replaces the in-chart stats table; keep it available but off by default
    out = out.replace('bool   showStats   = input.bool(true, "Show backtest stats"',
                      'bool   showStats   = input.bool(false, "Show backtest stats"', 1)

    for marker, code in (("// <<STRATEGY_STATE>>\n", STATE),
                         ("        // <<STRATEGY_ENTRY>>\n", ENTRY),
                         ("// <<STRATEGY_MANAGE>>\n", MANAGE)):
        if out.count(marker) != 1:
            sys.exit(f"marker not found exactly once: {marker.strip()}")
        out = out.replace(marker, code)
    return out


if __name__ == "__main__":
    DST.write_text(build(), encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
